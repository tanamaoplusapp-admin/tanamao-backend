'use strict';
const express=require('express');const {verifyToken}=require('../middleware/verifyToken');
const rateLimit=require('express-rate-limit');const {asyncHandler,guardEnabled,betaGuard,privateError}=require('../middleware/mobilidade');
const c=require('../controllers/mobilidadeController');const buscaCliente=require('../services/mobilidadeBuscaCliente');const lugares=require('../services/mobilidadeLugares');const router=express.Router();
const limited=rateLimit({windowMs:60000,max:50,standardHeaders:true,legacyHeaders:false});
router.use(guardEnabled,verifyToken,betaGuard);
router.get('/catalogo',asyncHandler(c.catalog));
// Busca de enderecos, detalhes e selecao no mapa: autenticadas e limitadas.
const placesLimited=rateLimit({windowMs:60000,max:40,standardHeaders:true,legacyHeaders:false, keyGenerator:req=>String(req.userId||req.ip)});
const buscaLimited=rateLimit({windowMs:60000,max:8,standardHeaders:true,legacyHeaders:false, keyGenerator:req=>String(req.userId||req.ip)});
// Consulta pre-cotacao de permissao territorial de passageiro por moto.
router.post('/cliente/modalidades',placesLimited,asyncHandler(c.modalidadesOrigem));
router.post('/cliente/lugares/sessao',placesLimited,asyncHandler(lugares.criarSessao));
router.post('/cliente/lugares/sugestoes',placesLimited,asyncHandler(lugares.sugestoes));
router.post('/cliente/lugares/detalhes',placesLimited,asyncHandler(lugares.detalhes));
router.post('/cliente/lugares/reverso',placesLimited,asyncHandler(lugares.reverso));
router.get('/motorista/perfil',asyncHandler(c.getProfile));
router.put('/motorista/perfil',limited,asyncHandler(c.setProfile));
router.post('/motorista/foto/revisao',limited,asyncHandler(c.solicitarRevisaoFoto));
router.put('/motorista/cnh',limited,asyncHandler(c.setCNH));
router.get('/motorista/documentos',asyncHandler(c.listDocuments));
router.post('/motorista/documentos',limited,(req,res,next)=>c.upload(req,res,err=>{if(err){return res.status(400).json({ok:false,erro:err.code==='LIMIT_FILE_SIZE'?'Arquivo maior que 5MB':err.message});}next();}),asyncHandler(c.uploadDocument));
router.get('/motorista/veiculos',asyncHandler(c.listVehicles));
router.post('/motorista/veiculos',limited,asyncHandler(c.createVehicle));
router.put('/motorista/veiculos/:vehicleId',limited,asyncHandler(c.updateVehicle));
router.post('/motorista/veiculos/:vehicleId/selecionar',asyncHandler(c.selectVehicle));
router.post('/motorista/veiculos/:vehicleId/manutencoes',limited,asyncHandler(c.addMaintenance));
router.get('/motorista/veiculos/:vehicleId/manutencoes',asyncHandler(c.getMaintenance));
router.get('/motorista/disponibilidade',asyncHandler(c.getAvailability));
router.patch('/motorista/disponibilidade',limited,asyncHandler(c.setAvailability));
router.post('/motorista/localizacao',limited,asyncHandler(c.setLocation));
router.get('/motorista/resumo',asyncHandler(c.getDriverDashboard));
router.get('/motorista/ofertas',asyncHandler(c.getDriverOffers));
router.get('/motorista/areas-demanda',asyncHandler(c.getDemandAreas));
router.post('/motorista/ofertas/:jobId/aceitar',limited,asyncHandler(c.acceptOffer));
router.post('/motorista/ofertas/:jobId/recusar',limited,asyncHandler(c.rejectOffer));
router.get('/motorista/viagens',asyncHandler(c.driverTrips));
router.get('/motorista/avaliacoes',asyncHandler(c.driverRatings));
router.post('/motorista/viagens/:jobId/cheguei',limited,asyncHandler(c.driverArrive));
router.post('/motorista/viagens/:jobId/iniciar',limited,asyncHandler(c.startTrip));
router.post('/motorista/viagens/:jobId/finalizar',limited,asyncHandler(c.finishTrip));
router.post('/motorista/viagens/:jobId/pagamento/recebido',limited,asyncHandler(c.driverPaymentReceived));
router.post('/cliente/cotacoes',limited,asyncHandler(c.quote));
router.post('/cliente/solicitacoes',limited,asyncHandler(c.createRequest));
router.get('/cliente/solicitacoes',asyncHandler(c.listClientJobs));
router.get('/solicitacoes/:jobId',asyncHandler(c.readJob));
router.get('/cliente/solicitacoes/:jobId/motorista',asyncHandler(c.clientDriverTracking));
router.get('/cliente/solicitacoes/:jobId/busca',buscaLimited,asyncHandler(buscaCliente.buscar));
router.post('/cliente/solicitacoes/:jobId/cancelar',limited,asyncHandler(c.clientCancel));
router.post('/cliente/solicitacoes/:jobId/pagamento/avaliar',limited,asyncHandler(c.clientPaymentReview));
router.post('/cliente/solicitacoes/:jobId/avaliacao',limited,asyncHandler(c.reviewTrip));
router.get('/solicitacoes/:jobId/mensagens/rapidas',asyncHandler(c.mensagensRapidas));
router.get('/solicitacoes/:jobId/mensagens',asyncHandler(c.messages));
router.post('/solicitacoes/:jobId/mensagens',limited,asyncHandler(c.messages));
router.use(privateError);
module.exports=router;
